"""Load test of the FR-10 lock layer: N concurrent requests through the full pipeline on a fresh database.

    python scripts/lock_load_test.py [requests=500] [collaterals=50]
        -> artifacts/reports/lock_load_test.json, lock_load_test.md

Every request is a strong applicant (would be auto-approved) with its own Loan_ID and Applicant_ID; requests are
spread over `collaterals` collateral ids, so exactly one approval per collateral is allowed. All threads are
released together by a barrier.
"""
import json
import sys
import threading
import time
import warnings
from concurrent.futures import ThreadPoolExecutor

import numpy as np

from cognilend import config
from cognilend.db.models import Loan
from cognilend.db.repository import FallbackLog, Repository
from cognilend.demo import BASE
from cognilend.pipeline import DecisionPipeline


def run(n: int = 500, collaterals: int = 50) -> dict:
    warnings.filterwarnings('ignore', message='.*sklearn.utils.parallel.delayed.*')
    d = config.ROOT / 'data' / 'processed' / 'loadtest'
    d.mkdir(parents=True, exist_ok=True)
    db = d / 'load.db'
    for suffix in ('', '-wal', '-shm'):
        p = db.with_name(db.name + suffix)
        if p.exists():
            p.unlink()
    repo = Repository(f'sqlite:///{db.as_posix()}')
    pipe = DecisionPipeline(repo=repo, fallback=FallbackLog(d / 'fallback.jsonl'))
    pipe.explainer                                       # load artefacts before the race
    barrier = threading.Barrier(n)

    def one(i):
        barrier.wait()
        t0 = time.perf_counter()
        out = pipe.decide({**BASE, 'Loan_ID': f'LT{i:04d}', 'Applicant_ID': f'LTA{i:04d}',
                           'Collateral_ID': f'COLL-{i % collaterals:03d}'}, batch_id='load')
        out['e2e_ms'] = (time.perf_counter() - t0) * 1000
        return out

    t0 = time.perf_counter()
    with ThreadPoolExecutor(max_workers=n) as ex:
        results = list(ex.map(one, range(n)))
    wall = time.perf_counter() - t0
    with repo.Session() as s:
        approved = s.query(Loan).filter(Loan.status == 'APPROVED').all()
    approved_colls = [int(ln.loan_id[2:]) % collaterals for ln in approved]
    lock_ms = np.array([r['lock_latency_ms'] for r in results if r.get('lock_latency_ms') is not None])
    e2e = np.array([r['e2e_ms'] for r in results])
    out = {
        'requests': n, 'collaterals': collaterals, 'wall_seconds': round(wall, 2),
        'throughput_per_s': round(n / wall, 1),
        'approved': sum(r['decision'] == 'Approved' for r in results),
        'human_review': sum(r['decision'] == 'Human Review' for r in results),
        'other': sum(r['decision'] not in ('Approved', 'Human Review') for r in results),
        'approved_loans_in_db': len(approved),
        'max_approvals_per_collateral': int(max(np.bincount(approved_colls, minlength=collaterals))) if approved else 0,
        'collaterals_with_exactly_one_approval': int((np.bincount(approved_colls, minlength=collaterals) == 1).sum()),
        'persisted': sum(bool(r['persisted']) for r in results), 'fallback': sum(bool(r['fallback_id']) for r in results),
        'chain': str(repo.verify_chain()),
        'lock_latency_ms': {k: round(float(np.percentile(lock_ms, q)), 1) for k, q in
                            (('p50', 50), ('p95', 95), ('p99', 99))} | {'max': round(float(lock_ms.max()), 1)},
        'end_to_end_ms': {k: round(float(np.percentile(e2e, q)), 1) for k, q in
                          (('p50', 50), ('p95', 95), ('p99', 99))} | {'max': round(float(e2e.max()), 1)},
        'note': 'lock latency = time inside record_decision (waiting for the SQLite write lock + lock check + '
                'writes + commit); end-to-end = full pipeline.decide incl. rules and model',
    }
    out['pass'] = (out['approved'] == collaterals == out['approved_loans_in_db']
                   and out['max_approvals_per_collateral'] == 1 and out['other'] == 0
                   and out['persisted'] == n and out['chain'] == 'OK')
    repo.engine.dispose()
    return out


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 500
    c = int(sys.argv[2]) if len(sys.argv) > 2 else 50
    r = run(n, c)
    rep = config.ROOT / config.load('settings')['paths']['reports']
    (rep / 'lock_load_test.json').write_text(json.dumps(r, indent=2), encoding='utf-8')
    md = ['# Lock-layer load test', '', 'Generated by `python scripts/lock_load_test.py`.', '',
          f'{r["requests"]} concurrent requests (one barrier release) over {r["collaterals"]} collaterals, fresh '
          f'SQLite database, full pipeline per request.', '',
          '| Measure | Value |', '|---|---|']
    for k in ('wall_seconds', 'throughput_per_s', 'approved', 'human_review', 'other', 'approved_loans_in_db',
              'max_approvals_per_collateral', 'collaterals_with_exactly_one_approval', 'persisted', 'fallback',
              'chain'):
        md.append(f'| {k} | {r[k]} |')
    md.append(f'| lock latency ms (p50 / p95 / p99 / max) | {" / ".join(str(v) for v in r["lock_latency_ms"].values())} |')
    md.append(f'| end-to-end ms (p50 / p95 / p99 / max) | {" / ".join(str(v) for v in r["end_to_end_ms"].values())} |')
    md += ['', f'**Result: {"PASS" if r["pass"] else "FAIL"}** (exactly one approval per collateral, every request '
           'decided and persisted, audit chain intact).', '', r['note']]
    (rep / 'lock_load_test.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
