"""F5: compare the post-feature state with the F0 baseline -> reports/feature_max_amount_regression.md.

    python scripts/addons/regression_report.py

Inputs (produced beforehand): reports/baseline/* (F0), reports/pytest_after_original.txt,
reports/pytest_after_addons.txt, reports/decisions_after.csv(.sha256), reports/db_row_counts_after.json,
reports/file_hashes_after.json.
"""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
R, BASE = ROOT / 'reports', ROOT / 'reports' / 'baseline'
UI_FILE = 'app/pages/1_New_Application.py'
# rewritten with fresh timings by the ORIGINAL test suite on every run (tests/test_db.py), not by the add-on
VOLATILE = {'artifacts/reports/lock_latency.json': 'timing file rewritten by the original test suite on every run'}


def results(path: Path) -> dict:
    txt = path.read_text(encoding='utf-8', errors='replace')
    return dict((m.group(2), m.group(1)) for m in re.finditer(r'^(PASSED|FAILED|ERROR|SKIPPED|XFAIL|XPASS) (\S+)',
                                                              txt, re.M))


def summary_line(path: Path) -> str:
    lines = [x for x in path.read_text(encoding='utf-8', errors='replace').splitlines() if x.startswith('====')]
    return lines[-1].strip('= ') if lines else '?'


def main():
    rows = []

    def check(name, ok, detail):
        rows.append((name, 'PASS' if ok else 'FAIL', detail))

    before, after = results(BASE / 'pytest_before.txt'), results(R / 'pytest_after_original.txt')
    check('1. Original test suite: same tests, same results', before == after and len(before) > 0,
          f'before: {summary_line(BASE / "pytest_before.txt")}; after: {summary_line(R / "pytest_after_original.txt")}')

    hb = json.loads((BASE / 'file_hashes_before.json').read_text())
    ha = json.loads((R / 'file_hashes_after.json').read_text())
    orig_tests = [k for k in hb if k.startswith('tests/')]
    check('1b. No original test file edited (sha256)', all(ha.get(k) == hb[k] for k in orig_tests),
          f'{len(orig_tests)} original test files compared')

    sb = (BASE / 'decisions_before.csv.sha256').read_text().split()[0]
    sa = (R / 'decisions_after.csv.sha256').read_text().split()[0]
    bytes_equal = (BASE / 'decisions_before.csv').read_bytes() == (R / 'decisions_after.csv').read_bytes()
    check('2. decide_many on the test split: byte-identical decisions', sb == sa and bytes_equal, f'sha256 {sa}')

    changed = sorted(k for k in hb if ha.get(k) != hb[k])
    unexpected = [k for k in changed if k not in VOLATILE and k != UI_FILE]
    added = sorted(k for k in ha if k not in hb)
    check('3. Existing files unchanged except the UI file', not unexpected,
          f'changed: {changed}; unexpected: {unexpected or "none"}')
    diff = subprocess.run(['git', 'diff', '-U0', 'main', '--', UI_FILE], cwd=ROOT, capture_output=True,
                          text=True).stdout
    plus = [x for x in diff.splitlines() if x.startswith('+') and not x.startswith('+++')]
    minus = [x for x in diff.splitlines() if x.startswith('-') and not x.startswith('---')]
    check('3b. UI file: exactly 2 added lines, 0 removed', len(plus) == 2 and not minus,
          '<br>'.join(f'`{x}`' for x in plus))
    req = subprocess.run(['git', 'diff', '--quiet', 'main', '--', 'requirements.txt'], cwd=ROOT).returncode == 0
    check('3c. requirements.txt unchanged', req, 'no new package needed')

    cb = json.loads((BASE / 'db_row_counts_before.json').read_text())
    ca = json.loads((R / 'db_row_counts_after.json').read_text())
    check('4. Existing table row counts after decide_many match', cb == ca, json.dumps(ca))

    addon = results(R / 'pytest_after_addons.txt')
    check('5. Add-on tests all pass', addon and all(v == 'PASSED' for v in addon.values()),
          summary_line(R / 'pytest_after_addons.txt'))

    stat = subprocess.run(['git', 'diff', '--stat', 'main...feature/max-approvable-amount'], cwd=ROOT,
                          capture_output=True, text=True).stdout
    md = ['# Max approvable amount: regression check against the F0 baseline', '',
          'Generated by `python scripts/addons/regression_report.py`.', '',
          f'**Overall: {"PASS" if all(r[1] == "PASS" for r in rows) else "FAIL"}**', '',
          '| Check | Result | Detail |', '|---|---|---|']
    md += [f'| {n} | {ok} | {d} |' for n, ok, d in rows]
    md += ['', '## Known volatile file', ''] + [f'- `{k}`: {v}. Not touched by the add-on.' for k, v in VOLATILE.items()]
    md += ['', '## New files under src/, config/, artifacts/, tests/, app/', ''] + [f'- `{k}`' for k in added]
    md += ['', '## `git diff --stat main...feature/max-approvable-amount`', '', '```', stat.rstrip(), '```', '']
    (R / 'feature_max_amount_regression.md').write_text('\n'.join(md), encoding='utf-8')
    for r in rows:
        print(r[1], r[0])


if __name__ == '__main__':
    main()
