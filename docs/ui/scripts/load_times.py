"""Page load time, old UI (git main) vs new UI: full server-side run of each page script.

    python docs/ui/scripts/load_times.py <out.md>

A Streamlit page is ready when its script run finishes. Each page of both UIs is run headlessly with streamlit
AppTest against the same database and models: one warm-up run, then 5 runs alternating old / new (median).
Browser timings were tried first and rejected: Streamlit's delayed "running" indicator and periodic websocket
messages made the spread between identical runs larger than the difference being measured.
"""
import shutil
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PAGES = [('Home', 'streamlit_app.py', 'views/home.py', {}),
         ('New Application', 'pages/1_New_Application.py', 'pages/1_New_Application.py', {}),
         ('New Application (demo result)', 'pages/1_New_Application.py', 'pages/1_New_Application.py',
          {'demo': 'auto_approve'}),
         ('Review Queue', 'pages/2_Officer_Review_Queue.py', 'pages/2_Officer_Review_Queue.py', {}),
         ('Audit Explorer', 'pages/3_Audit_Explorer.py', 'pages/3_Audit_Explorer.py', {'q': 'DEMO-LOCK'}),
         ('Model & Policy', 'pages/4_Model_and_Policy.py', 'pages/4_Model_and_Policy.py', {}),
         ('Fairness', 'pages/5_Fairness_Dashboard.py', 'pages/5_Fairness_Dashboard.py', {}),
         ('Stress Twin', 'pages/6_Stress_Twin.py', 'pages/6_Stress_Twin.py', {}),
         ('Model Comparison', 'pages/7_Model_Comparison.py', 'pages/7_Model_Comparison.py', {})]


def timed(app_dir: Path, rel: str, qp: dict) -> float:
    from streamlit.testing.v1 import AppTest
    sys.path.insert(0, str(app_dir))
    for m in [m for m in sys.modules if m in ('common', 'components', 'components.max_amount_panel', 'ui')
              or m.startswith('ui.')]:
        del sys.modules[m]
    try:
        at = AppTest.from_file(str(app_dir / rel), default_timeout=300)
        for k, v in qp.items():
            at.query_params[k] = v
        t0 = time.perf_counter()
        at.run()
        return time.perf_counter() - t0
    finally:
        sys.path.remove(str(app_dir))


def main(n: int = 5):
    rows = []
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        tmp = Path(tmp)
        (tmp / 'old.tar').write_bytes(subprocess.run(['git', 'archive', 'main', 'app'], cwd=ROOT, capture_output=True,
                                                     check=True).stdout)
        shutil.unpack_archive(tmp / 'old.tar', tmp / 'old', 'tar')
        old_app, new_app = tmp / 'old' / 'app', ROOT / 'app'
        for name, o_rel, n_rel, qp in PAGES:
            timed(old_app, o_rel, qp)
            timed(new_app, n_rel, qp)
            to, tn = [], []
            for _ in range(n):
                to.append(timed(old_app, o_rel, qp))
                tn.append(timed(new_app, n_rel, qp))
            rows.append((name, statistics.median(to), statistics.median(tn)))
            print(name, f'{rows[-1][1]:.2f} -> {rows[-1][2]:.2f}', flush=True)
    lines = ['# Page load times: server-side script run (median of 5 interleaved runs)', '',
             'Generated by `docs/ui/scripts/load_times.py`.', '', '| Page | Before (s) | After (s) | Change |',
             '|---|---|---|---|']
    lines += [f'| {a} | {o:.2f} | {nn:.2f} | {nn - o:+.2f} s |' for a, o, nn in rows]
    to, tn = sum(r[1] for r in rows), sum(r[2] for r in rows)
    lines += ['', f'Total: {to:.2f} s before, {tn:.2f} s after ({tn - to:+.2f} s, {(tn - to) / to:+.0%}).']
    Path(sys.argv[1]).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
