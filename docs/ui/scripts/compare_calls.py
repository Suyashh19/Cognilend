"""Run the call-log stories on the OLD UI (git main) and the NEW UI against the same DB snapshot and diff them.

    python docs/ui/scripts/compare_calls.py <out_dir>

1. copy data/processed/cognilend.db (+ -wal/-shm) aside;
2. extract app/ from git main into a temp folder and run call_log.py on it (old);
3. restore the DB copy, run call_log.py on ./app (new);
4. restore the DB copy again (the stories leave no trace), write old.json, new.json and diff.md.

Compared per story: the sequence of ACTION calls (decide, complete_review, verify_chain, decision_history,
find_max_approvable_amount, disparate_impact.run, simulate) with their arguments and results. Read-only calls
made only to draw the new screens (summary, versions, list_reviews, audit_event, fairness_*) are listed but not
required to match.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DB = ROOT / 'data' / 'processed' / 'cognilend.db'
ACTIONS = ('decide', 'complete_review', 'verify_chain', 'decision_history', 'find_max_approvable_amount',
           'disparate_impact.run', 'simulate')


def snapshot(dst: Path):
    for suf in ('', '-wal', '-shm'):
        p = DB.with_name(DB.name + suf)
        if p.exists():
            shutil.copy2(p, dst / p.name)


def restore(src: Path):
    for suf in ('', '-wal', '-shm'):
        p = DB.with_name(DB.name + suf)
        s = src / p.name
        if p.exists():
            p.unlink()
        if s.exists():
            shutil.copy2(s, p)


def run(app_dir: Path, mode: str, out: Path):
    env = {**os.environ, 'PYTHONIOENCODING': 'utf-8'}
    r = subprocess.run([sys.executable, str(ROOT / 'docs' / 'ui' / 'scripts' / 'call_log.py'), str(app_dir), mode,
                        str(out)], cwd=ROOT, env=env, capture_output=True, text=True, encoding='utf-8')
    print(r.stdout[-4000:], r.stderr[-3000:] if r.returncode else '')
    if r.returncode:
        raise SystemExit(f'call_log failed for {mode}')


GENERATED = re.compile(r'^(APP-)?LN-[0-9a-f]{16}$')     # ids the backend draws at random (uuid4) when none is given


def _mask(x):
    if isinstance(x, dict):
        return {k: _mask(v) for k, v in x.items()}
    if isinstance(x, list):
        return [_mask(v) for v in x]
    return '<generated id>' if isinstance(x, str) and GENERATED.match(x) else x


def actions(story: dict, name: str = '') -> list:
    """Action calls of a story. decision_history is the Audit page's search action; elsewhere the new UI uses it
    read-only (the Review Queue's explanation drawer), so it only counts in audit_* stories."""
    out = []
    for c in story.get('calls', []):
        if c['call'] in ACTIONS and (c['call'] != 'decision_history' or name.startswith('audit')):
            out.append(_mask({k: c.get(k) for k in ('call', 'args', 'kwargs', 'batch_id', 'result') if k in c}))
    return out


def main():
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        tmp = Path(tmp)
        (tmp / 'db').mkdir()
        snapshot(tmp / 'db')
        old_app = tmp / 'old'
        old_app.mkdir()
        tar = subprocess.run(['git', 'archive', 'main', 'app'], cwd=ROOT, capture_output=True, check=True).stdout
        (tmp / 'old.tar').write_bytes(tar)
        shutil.unpack_archive(tmp / 'old.tar', old_app, 'tar')
        try:
            run(old_app / 'app', 'old', out / 'old.json')
            restore(tmp / 'db')
            run(ROOT / 'app', 'new', out / 'new.json')
        finally:
            restore(tmp / 'db')
    old = json.loads((out / 'old.json').read_text(encoding='utf-8'))
    new = json.loads((out / 'new.json').read_text(encoding='utf-8'))
    lines = ['# Backend calls: old UI vs new UI', '', 'Same DB snapshot for both runs; generated by '
             '`docs/ui/scripts/compare_calls.py`.', '', '| Story | Old ok | New ok | Action calls (old / new) | '
             'Identical | Extra read-only calls in new UI |', '|---|---|---|---|---|---|']
    all_ok = True
    for name in old:
        o, n = old[name], new.get(name, {'ok': False, 'calls': []})
        ao, an = actions(o, name), actions(n, name)
        same = ao == an and o['ok'] and n['ok']
        all_ok &= same
        extra = sorted({c['call'] for c in n['calls'] if c['call'] not in ACTIONS or
                        (c['call'] == 'decision_history' and not name.startswith('audit'))})
        lines.append(f'| {name} | {o["ok"]} | {n["ok"]} | {len(ao)} / {len(an)} | {"PASS" if same else "FAIL"} | '
                     f'{", ".join(extra) or "—"} |')
        if not same:  # noqa: SIM102
            lines += ['', f'<details><summary>{name} differs</summary>', '', '```json',
                      json.dumps({'old': ao, 'new': an, 'old_error': o.get('error'), 'new_error': n.get('error')},
                                 indent=1, default=str)[:12000], '```', '</details>', '']
    lines += ['', f'**Overall: {"PASS" if all_ok else "FAIL"}**']
    (out / 'diff.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))
    raise SystemExit(0 if all_ok else 1)


if __name__ == '__main__':
    main()
