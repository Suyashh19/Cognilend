"""WCAG 2.1 contrast check of every text / background pair the design system uses, light and dark.

    python docs/ui/scripts/contrast.py [out.md]

Pairs come from app/ui/theme.py (TOKENS) and .streamlit/config.toml (theme colours). Text pairs need >= 4.5:1
(AA, normal text); large display text (>= 24px, the outcome headline and the suggested amount) needs >= 3:1, but
we hold it to 4.5 as well. Non-text indicators (meter fill, borders) are listed for information at 3:1.
"""
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
import os
CFG = Path(os.environ.get('CL_CFG', ROOT / '.streamlit' / 'config.toml'))
sys.path.insert(0, str(ROOT / 'app'))

from ui.theme import TOKENS  # noqa: E402


def lum(hex_: str) -> float:
    h = hex_.lstrip('#')
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))

    def ch(c):
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def ratio(a: str, b: str) -> float:
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


TEXT_PAIRS = [  # (description, text token, background token)
    ('body text on page', 'text', 'bg'), ('body text on card', 'text', 'surface'),
    ('muted text on page', 'muted', 'bg'), ('muted text on card', 'muted', 'surface'),
    ('muted text on neutral chip', 'muted-ink', 'neutral-soft'),
    ('primary link / pill text on card', 'primary-ink', 'surface'), ('pill text on pill', 'primary-ink', 'primary-soft'),
    ('text on primary button', 'on-primary', 'primary'),
    ('Approved badge', 'approve-ink', 'approve-soft'), ('Approved text on card', 'approve-ink', 'surface'),
    ('Rejected badge', 'reject-ink', 'reject-soft'), ('Rejected text on card', 'reject-ink', 'surface'),
    ('Human Review badge', 'review-ink', 'review-soft'), ('Human Review text on card', 'review-ink', 'surface'),
    ('field hint (error) on page', 'reject-ink', 'bg'), ('text on neutral chip', 'text', 'neutral-soft'),
]
NONTEXT = [('confidence meter fill vs track', 'primary', 'neutral-soft'), ('Approved bar vs card', 'approve', 'surface'),
           ('Rejected bar vs card', 'reject', 'surface'), ('Human Review bar vs card', 'review', 'surface')]


def main():
    out = []
    ok_all = True
    cfg = tomllib.loads((CFG).read_text(encoding='utf-8'))['theme']
    for mode in ('light', 'dark'):
        t = TOKENS[mode]
        out += [f'\n## {mode.title()} mode\n', '| Pair | Text | Background | Ratio | Need | Result |', '|---|---|---|---|---|---|']
        for desc, fg, bg in TEXT_PAIRS:
            r = ratio(t[fg], t[bg])
            ok = r >= 4.5
            ok_all &= ok
            out.append(f'| {desc} | `{t[fg]}` | `{t[bg]}` | {r:.2f}:1 | 4.5 | {"PASS" if ok else "FAIL"} |')
        s = cfg[mode]
        for desc, fg, bg in [('Streamlit text on background', 'textColor', 'backgroundColor'),
                             ('Streamlit text on secondary background', 'textColor', 'secondaryBackgroundColor'),
                             ('Streamlit link on background', 'linkColor', 'backgroundColor'),
                             ('Streamlit green text on green background', 'greenTextColor', 'greenBackgroundColor'),
                             ('Streamlit red text on red background', 'redTextColor', 'redBackgroundColor'),
                             ('Streamlit orange text on orange background', 'orangeTextColor', 'orangeBackgroundColor'),
                             ('Streamlit blue text on blue background (st.info)', 'blueTextColor', 'blueBackgroundColor')]:
            r = ratio(s[fg], s[bg])
            ok = r >= 4.5
            ok_all &= ok
            out.append(f'| {desc} | `{s[fg]}` | `{s[bg]}` | {r:.2f}:1 | 4.5 | {"PASS" if ok else "FAIL"} |')
        for desc, fg, bg in NONTEXT:
            r = ratio(t[fg], t[bg])
            ok = r >= 3
            ok_all &= ok
            out.append(f'| {desc} (non-text) | `{t[fg]}` | `{t[bg]}` | {r:.2f}:1 | 3.0 | {"PASS" if ok else "FAIL"} |')
    text = '# Contrast report (WCAG 2.1 AA)\n\nGenerated by `docs/ui/scripts/contrast.py`.\n' + '\n'.join(out) + \
        f'\n\n**Overall: {"PASS" if ok_all else "FAIL"}**\n'
    if len(sys.argv) > 1:
        Path(sys.argv[1]).write_text(text, encoding='utf-8')
    print(text)
    raise SystemExit(0 if ok_all else 1)


if __name__ == '__main__':
    main()
