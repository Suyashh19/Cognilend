"""Max approvable amount on every REJECTED application of the TEST split, confirmed by the NORMAL pipeline.

    python scripts/addons/max_amount_eval.py   -> reports/feature_max_amount_eval.md, reports/feature_max_amount_eval.csv

For every suggestion with possible=True, pipeline.decide (the real, persisting DecisionPipeline) is run on a copy
of the application with the suggested amount against a THROWAWAY database: it must return Approved.
"""
import json
import sys
import tempfile
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'scripts'))

from evaluate_pipeline import test_applications  # noqa: E402
from cognilend.addons.dry_run import decisions_without_saving  # noqa: E402
from cognilend.addons.max_amount import find_max_approvable_amount  # noqa: E402
from cognilend.db.repository import Repository  # noqa: E402
from cognilend.pipeline import DecisionPipeline  # noqa: E402


def rejected_test_apps(limit: int | None = None) -> list[dict]:
    df, _ = test_applications()
    apps = [{k: v for k, v in r.items() if not (v is None or (isinstance(v, float) and np.isnan(v)))}
            for r in df.to_dict('records')]
    dec = decisions_without_saving(apps)
    out = [a for a, d in zip(apps, dec) if d == 'Rejected']
    return out[:limit] if limit else out


def evaluate(apps: list[dict]) -> pd.DataFrame:
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        repo = Repository(f'sqlite:///{Path(tmp).as_posix()}/confirm.db')
        real = DecisionPipeline(repo=repo)
        for app in apps:
            r = find_max_approvable_amount(app)
            confirmed = None
            if r.get('possible'):
                d = real.decide({**app, 'Loan_Amount': r['max_amount']}, batch_id='max-amount-confirm')
                confirmed = d['decision']
            rows.append({'loan_id': app.get('Loan_ID'), 'requested': r.get('requested_amount'),
                         'possible': r.get('possible'), 'max_amount': r.get('max_amount'),
                         'binding_limit': r.get('binding_limit'), 'confidence_at_max': r.get('confidence_at_max'),
                         'candidates_checked': r.get('candidates_checked'), 'runtime_ms': r.get('runtime_ms'),
                         'pipeline_decision_at_max': confirmed})
        repo.engine.dispose()
    return pd.DataFrame(rows)


def summary(df: pd.DataFrame) -> dict:
    pos = df[df['possible'] == True]  # noqa: E712
    ok = (pos['pipeline_decision_at_max'] == 'Approved').sum()
    return {'rejected_cases': int(len(df)), 'possible': int(len(pos)), 'not_possible': int(len(df) - len(pos)),
            'confirmed_approved': int(ok), 'success_rate': float(ok / len(pos)) if len(pos) else 1.0,
            'runtime_ms_p50': float(df['runtime_ms'].quantile(0.50)),
            'runtime_ms_p95': float(df['runtime_ms'].quantile(0.95)),
            'runtime_ms_max': float(df['runtime_ms'].max()),
            'binding_limits': df['binding_limit'].value_counts().to_dict()}


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    df = evaluate(rejected_test_apps())
    s = summary(df)
    out = ROOT / 'reports'
    df.to_csv(out / 'feature_max_amount_eval.csv', index=False)
    md = ['# Max approvable amount on the rejected TEST-split applications', '',
          'Generated by `python scripts/addons/max_amount_eval.py`. Each suggested amount is re-submitted to the normal '
          '`DecisionPipeline.decide` against a throwaway database.', '',
          '| Metric | Value |', '|---|---|'] + [f'| {k} | {v} |' for k, v in s.items()]
    (out / 'feature_max_amount_eval.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
    print(json.dumps(s, indent=1))
