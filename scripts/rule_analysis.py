"""Analyse every policy threshold on the cleaned TRAINING split and write docs/rule_justification.md.

    python scripts/rule_analysis.py

For each rule: how many applicants it fires on, the historical approval rate (label) when it fires vs not, and
the approval rate just either side of the cutoff. R03 also gets a cutoff sweep. All numbers in the generated
document come from this script; rationale and source text come from config/policies_v1.yaml.
"""
import json
import sys

import numpy as np
import pandas as pd

from cognilend import config
from cognilend.data import preprocess
from cognilend.rules import engine
from cognilend.rules.rules import load_policy, load_rules

WINDOWS = {'R01': ('age', 2), 'R03': ('age_at_maturity', 2), 'R04': ('cibil_score', 25), 'R05': ('foir', 0.05),
           'R06': ('ltv', 0.05), 'R07': ('total_income', 3000), 'S02': ('work_experience', 1)}


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    clean = pd.read_parquet(preprocess.processed_dir() / 'clean.parquet')
    train = clean[clean['split'] == 'train'].reset_index(drop=True)
    results = [engine.evaluate_clean(r) for r in train.to_dict('records')]
    y = train['target'].to_numpy()
    facts = pd.DataFrame([r['facts'] for r in results])
    status = pd.DataFrame([{e['rule_id']: e['status'] for e in r['evaluations']} for r in results])
    outcome = pd.Series([r['outcome'] for r in results])
    policy = load_policy('v1')
    rules = load_rules(policy)
    n = len(train)

    md = ['# Rule justification (policy v1)', '',
          'Generated by `python scripts/rule_analysis.py` on the cleaned **training** split '
          f'(n = {n:,}). "Approval rate" is the historical label. In the primary dataset the label comes from a '
          'latent repayment-risk score that does not use the rules (docs/data_decision.md), so a rule that the '
          'label ignores (e.g. age at maturity) shows little difference either side of its cutoff. Such rules '
          'rest on policy and regulation, not on the label, and the tables show their cost: how many applicants '
          'each one rejects or routes to review.', '',
          '## Overall outcome of the rule layer (training split)', '',
          '| Outcome | n | share | historical approval rate |', '|---|---|---|---|']
    invalid = pd.Series(['INPUT' in r['fired_rules'] for r in results]).to_numpy()
    buckets = {'REJECT (invalid input: required field missing after cleaning)': invalid,
               'REJECT (HARD rule)': (outcome == 'REJECT').to_numpy() & ~invalid,
               'REVIEW (SOFT rule)': (outcome == 'REVIEW').to_numpy(), 'PASS': (outcome == 'PASS').to_numpy()}
    summary = {'n_train': int(n), 'buckets': {}, 'rules': [], 'r03_sweep': []}
    for o, m in buckets.items():
        md.append(f'| {o} | {m.sum():,} | {m.mean():.3f} | {y[m].mean():.3f} |')
        summary['buckets'][o] = {'n': int(m.sum()), 'share': float(m.mean()), 'approval_rate': float(y[m].mean())}
    md += ['', 'Rule columns below count only the applications that passed input validation; for the invalid ones '
           'no rule is evaluated.']
    md += ['', '## Per rule', '',
           '| Rule | Type | Condition | fired | share | approval if fired | approval otherwise | '
           'exempt / n.a. / not evaluated |', '|---|---|---|---|---|---|---|---|']
    for r in rules:
        s = status[r.id]
        fired = (s == 'fired').to_numpy()
        other = (s == 'passed').to_numpy()
        a_f = f'{y[fired].mean():.3f}' if fired.any() else '-'
        a_o = f'{y[other].mean():.3f}' if other.any() else '-'
        summary['rules'].append({'id': r.id, 'type': r.type, 'fired': int(fired.sum()), 'share': float(fired.mean()),
                                 'approval_if_fired': float(y[fired].mean()) if fired.any() else None,
                                 'approval_otherwise': float(y[other].mean()) if other.any() else None})
        md.append(f'| {r.id} | {r.type} | `{r.condition}` | {fired.sum():,} | {fired.mean():.3f} | {a_f} | {a_o} | '
                  f'{(s == "exempt").sum()} / {(s == "not_applicable").sum()} / {(s == "not_evaluated").sum()} |')
    md += ['', 'R02 is "not evaluated" for every row because the historical file has no Applicant_ID; it is '
           'exercised by the unit tests and by live applications that supply one.']

    md += ['', '## Approval rate either side of each numeric cutoff', '',
           '| Rule | Fact | window | n just violating | approval | n just passing | approval |',
           '|---|---|---|---|---|---|---|']
    for r in rules:
        if r.id not in WINDOWS:
            continue
        fact, w = WINDOWS[r.id]
        s = status[r.id]
        v = pd.to_numeric(facts[fact], errors='coerce')
        thr = pd.to_numeric(facts[r.threshold_fact], errors='coerce') if r.threshold_fact else r.threshold
        near = (v - thr).abs() <= w
        viol = (near & (s == 'fired')).to_numpy()
        ok = (near & (s == 'passed')).to_numpy()
        fmt = lambda m: (f'{m.sum():,}', f'{y[m].mean():.3f}' if m.any() else '-')  # noqa: E731
        md.append(f'| {r.id} | {fact} | ±{w:g} | {fmt(viol)[0]} | {fmt(viol)[1]} | {fmt(ok)[0]} | {fmt(ok)[1]} |')

    md += ['', '## R03 cutoff sweep (age at maturity)', '',
           '| Cutoff | rejected by R03 | share | approval rate of those rejected |', '|---|---|---|---|']
    aam = pd.to_numeric(facts['age_at_maturity'], errors='coerce')
    for cut in (60, 62, 65, 68, 70):
        m = (aam > cut).to_numpy()
        summary['r03_sweep'].append({'cutoff': cut, 'rejected': int(m.sum()), 'share': float(m.mean()),
                                     'approval_of_rejected': float(y[m].mean()) if m.any() else None})
        md.append(f'| {cut} | {m.sum():,} | {m.mean():.3f} | {y[m].mean():.3f} |' if m.any()
                  else f'| {cut} | 0 | 0.000 | - |')
    old = ((facts['employment_type'] == 'Salaried') & (aam > 60)) | ((facts['employment_type'] != 'Salaried') & (aam > 65))
    md.append(f'| old split (Salaried 60 / self-employed 65) | {old.sum():,} | {old.mean():.3f} | '
              f'{y[old.to_numpy()].mean():.3f} |')

    md += ['', '## Rationale and source for each rule', '']
    for r in rules:
        md += [f'### {r.id} {r.name} ({r.type})', '', f'- Condition: `{r.condition}`',
               f'- Rationale: {r.rationale}', f'- Source: {r.source}', '']
    r03 = status['R03'] == 'fired'
    passed = (status['R03'] == 'passed').to_numpy()
    md += ['## R03 decision', '',
           f'The data does **not** support R03: applicants it rejects were historically approved at '
           f'{y[r03.to_numpy()].mean():.3f}, versus {y[passed].mean():.3f} for those it passes, because repayment '
           'risk in this dataset does not depend on age (older applicants have more experience, which the label '
           'rewards). R03 is therefore a policy constraint (no repayment after typical retirement), not a '
           'learned one, and its cost is the approvable applicants it turns away. The sweep shows that cost '
           f'falls from {(aam > 60).sum():,} rejections at 60 to {(aam > 65).sum():,} at 65 and '
           f'{(aam > 70).sum():,} at 70. v1 keeps a single cap of 65, the middle of the 60-70 range used by '
           'Indian lenders: it rejects about a third as many applicants as a 60 cap and removes the '
           'salaried/self-employed split. Recommendation for the October tuning: confirm 65 with the guide, or '
           'turn R03 into a SOFT rule (review instead of reject) for maturity ages 65-70.', '']
    (config.ROOT / config.load('settings')['paths']['reports'] / 'rule_analysis.json').write_text(
        json.dumps(summary, indent=2), encoding='utf-8')
    out = config.ROOT / 'docs' / 'rule_justification.md'
    out.write_text('\n'.join(md), encoding='utf-8')
    print('\n'.join(md[:40]))
    print('wrote', out)


if __name__ == '__main__':
    main()
