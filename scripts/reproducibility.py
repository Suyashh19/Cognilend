"""Run the full test split through the pipeline 3 times, each on a FRESH database with fixed artefact versions,
and compare the stored decisions.

    python scripts/reproducibility.py   -> artifacts/reports/reproducibility.md
"""
import hashlib
import json
import shutil
import sys
import time

import pandas as pd
from sqlalchemy import select

from cognilend import config
from cognilend.data import preprocess
from cognilend.db.models import Decision
from cognilend.db.repository import Repository
from cognilend.pipeline import DecisionPipeline

FIELDS = ['loan_id', 'source', 'outcome', 'confidence', 'reason', 'fired_rules_json', 'tree_path_json',
          'model_prediction', 'model_version', 'policy_version']


def artefact_hashes() -> dict:
    s = config.load('settings')
    out = {}
    for key, sub in (('preprocess', 'encoders'), ('model', 'models'), ('confidence', 'models')):
        p = config.ROOT / s['paths'][sub] / f"{s[key]['version']}.joblib"
        out[s[key]['version']] = hashlib.sha256(p.read_bytes()).hexdigest()[:16]
    pol = config.CONFIG_DIR / 'policies_v1.yaml'
    out['policies_v1'] = hashlib.sha256(pol.read_bytes()).hexdigest()[:16]
    return out


def one_run(i: int, csv) -> tuple[pd.DataFrame, float]:
    d = config.ROOT / 'data' / 'processed' / 'repro'
    d.mkdir(parents=True, exist_ok=True)
    db = d / f'run{i}.db'
    for suffix in ('', '-wal', '-shm'):
        p = db.with_name(db.name + suffix)
        if p.exists():
            p.unlink()
    repo = Repository(f'sqlite:///{db.as_posix()}')
    t0 = time.perf_counter()
    DecisionPipeline(repo=repo).decide_many(csv, batch_id='repro')
    secs = time.perf_counter() - t0
    with repo.Session() as s:
        rows = s.execute(select(Decision).where(Decision.batch_id == 'repro')).scalars().all()
        frame = pd.DataFrame([{f: getattr(r, f) for f in FIELDS} for r in rows]).sort_values('loan_id')
    chain = repo.verify_chain()
    repo.engine.dispose()
    frame.attrs['chain'] = str(chain)
    return frame.reset_index(drop=True), secs


def digest(frame: pd.DataFrame) -> str:
    return hashlib.sha256(frame.to_csv(index=False).encode()).hexdigest()


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    csv = preprocess.processed_dir() / 'test_applications.csv'
    if not csv.exists():
        raise SystemExit('run scripts/evaluate_pipeline.py first (it writes test_applications.csv)')
    n_in = len(pd.read_csv(csv, dtype=str))
    runs = [one_run(i, csv) for i in (1, 2, 3)]
    hashes = [digest(f) for f, _ in runs]
    identical = len(set(hashes)) == 1 and all(runs[0][0].equals(f) for f, _ in runs[1:])
    lines = ['# Reproducibility', '',
             'Generated by `python scripts/reproducibility.py`: the full test split run through '
             '`DecisionPipeline.decide_many` three times, each on a fresh SQLite database, with fixed artefacts.', '',
             f'Artefact versions (sha256 prefix): `{json.dumps(artefact_hashes())}`', '',
             '| Run | applications | decisions stored | audit chain | seconds | sha256 of stored decisions |',
             '|---|---|---|---|---|---|']
    for i, ((f, secs), h) in enumerate(zip(runs, hashes), 1):
        lines.append(f'| {i} | {n_in} | {len(f)} | {f.attrs["chain"]} | {secs:.1f} | `{h}` |')
    counts = runs[0][0]['outcome'].value_counts().to_dict()
    lines += ['', f'Compared fields: {", ".join(FIELDS)} (ids and timestamps excluded).', '',
              f'**Result: {"IDENTICAL" if identical else "DIFFERENT"}** across the three runs. Outcome counts: '
              f'{counts}.']
    if not identical:
        diff = (runs[0][0] != runs[1][0]).any(axis=1)
        lines.append(f'Differing rows (run 1 vs 2): {int(diff.sum())}')
    shutil.rmtree(config.ROOT / 'data' / 'processed' / 'repro', ignore_errors=True)
    md = '\n'.join(lines) + '\n'
    (config.ROOT / 'artifacts' / 'reports' / 'reproducibility.md').write_text(md, encoding='utf-8')
    print(md)
    if not identical:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
