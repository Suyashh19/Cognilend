"""Run the full TEST split through the integrated pipeline on a fresh database.

    python scripts/evaluate_pipeline.py
        -> data/processed/test_applications.csv  (cleaned test applications, input fields only)
        -> data/processed/cognilend.db           (fresh; batch_id = test-eval)
        -> artifacts/reports/pipeline_eval.md, pipeline_decisions.csv
"""
import sys
import time

import pandas as pd
from sqlalchemy import func, select

from cognilend import config
from cognilend.data import contract, preprocess
from cognilend.db.models import AuditLog, Decision, RuleResult
from cognilend.db.repository import Repository, make_engine
from cognilend.pipeline import REQUIRED_KEYS, DecisionPipeline

BATCH = 'test-eval'


def test_applications() -> pd.DataFrame:
    clean = pd.read_parquet(preprocess.processed_dir() / 'clean.parquet')
    ids = pd.read_parquet(preprocess.processed_dir() / 'test.parquet', columns=['Loan_ID'])['Loan_ID']
    rows = clean.set_index('Loan_ID').loc[ids].reset_index()
    cols = [c for c in contract.INPUT_FIELDS if c in rows.columns]
    return rows[cols], rows['target'].to_numpy()


def fresh_db_url() -> str:
    url = config.load('settings')['paths']['database_url']
    path = config.ROOT / url.replace('sqlite:///', '', 1)
    for suffix in ('', '-wal', '-shm'):
        p = path.with_name(path.name + suffix)
        if p.exists():
            p.unlink()
    return url


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    apps, y = test_applications()
    csv = preprocess.processed_dir() / 'test_applications.csv'
    apps.to_csv(csv, index=False)
    repo = Repository(fresh_db_url())
    pipe = DecisionPipeline(repo=repo)
    t0 = time.perf_counter()
    out = pipe.decide_many(csv, batch_id=BATCH)
    secs = time.perf_counter() - t0
    out.to_csv(config.ROOT / 'artifacts' / 'reports' / 'pipeline_decisions.csv', index=False)

    with repo.Session() as s:
        logged = s.execute(select(func.count()).select_from(Decision).where(Decision.batch_id == BATCH)).scalar_one()
        with_audit = s.execute(select(func.count()).select_from(Decision).where(
            Decision.batch_id == BATCH, Decision.audit_seq.is_not(None))).scalar_one()
        n_rule_rows = s.execute(select(func.count()).select_from(RuleResult)).scalar_one()
        n_audit = s.execute(select(func.count()).select_from(AuditLog)).scalar_one()
    chain = repo.verify_chain()
    complete = out[list(REQUIRED_KEYS)].notna().all(axis=1)

    n = len(out)
    out['label'] = y
    auto = out['decision'].isin(['Approved', 'Rejected'])
    model_auto = auto & (out['source'] == 'MODEL')
    pred = (out['decision'] == 'Approved').astype(int)
    lines = ['# Integrated pipeline on the test split', '',
             f'Generated by `python scripts/evaluate_pipeline.py` ({secs:.1f} s, {1000 * secs / n:.1f} ms per decision). '
             f'Fresh database, batch_id `{BATCH}`.', '',
             '## Coverage (FR-4)', '',
             f'- Applications in: **{n}**; decisions returned: **{len(out)}**; decision rows in DB for this batch: '
             f'**{logged}** -> coverage **{logged / n:.1%}**',
             f'- Decisions with an audit event: {with_audit}; audit chain: **{chain}** ({chain.checked} rows)',
             f'- Rule-result rows: {n_rule_rows:,}; outputs with all four parts (decision, confidence, reason, '
             f'audit ID): **{complete.sum()} / {n}**',
             f'- Written to fallback log instead of DB: {int((~out["persisted"]).sum())}', '',
             '## Outcome split', '', '| Decision | Source | n | share |', '|---|---|---|---|']
    for (dec, src), g in out.groupby(['decision', 'source']):
        lines.append(f'| {dec} | {src} | {len(g)} | {len(g) / n:.3f} |')
    lines += ['', f'- Auto-decided (Approved or Rejected by rules or model): **{auto.mean():.1%}**; '
              f'human review: **{(~auto).mean():.1%}**; dropped: **{n - len(out)}**', '',
              '## Agreement with the historical label', '',
              f'- Model auto-decisions: n = {model_auto.sum()}, accuracy vs label **'
              f'{(pred[model_auto] == out.loc[model_auto, "label"]).mean():.4f}**',
              f'- All auto-decisions incl. HARD-rule rejections: n = {auto.sum()}, agreement '
              f'{(pred[auto] == out.loc[auto, "label"]).mean():.4f}. HARD rules reject some applicants the '
              'historical label approved, by design (the label does not use the rules; docs/data_decision.md).',
              '', '## Most frequent fired rules', '', '| Rule | n |', '|---|---|']
    fired = out['fired_rules'].str.split(',').explode()
    for rule, c in fired[fired.astype(bool)].value_counts().items():
        lines.append(f'| {rule} | {c} |')
    md = '\n'.join(lines) + '\n'
    (config.ROOT / 'artifacts' / 'reports' / 'pipeline_eval.md').write_text(md, encoding='utf-8')
    print(md)


if __name__ == '__main__':
    main()
